CREATE TABLE refund_request (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 renewal_id BIGINT NOT NULL,
 account_id BIGINT NOT NULL,
 amount BIGINT NOT NULL,
 lessons DECIMAL(12,2) NOT NULL,
 gift_lessons DECIMAL(12,2) NOT NULL,
 reason VARCHAR(1000) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'REQUESTED',
 created_by BIGINT NOT NULL,
 created_at TIMESTAMP NOT NULL,
 updated_at TIMESTAMP NOT NULL,
 reviewed_by BIGINT,
 reviewed_at TIMESTAMP,
 review_note VARCHAR(1000) NOT NULL DEFAULT '',
 confirmed_by BIGINT,
 confirmed_at TIMESTAMP,
 payment_method VARCHAR(30),
 payment_reference VARCHAR(200) NOT NULL DEFAULT '',
 confirmation_note VARCHAR(1000) NOT NULL DEFAULT '',
 ledger_id BIGINT UNIQUE,
 version INT NOT NULL DEFAULT 0,
 FOREIGN KEY (renewal_id) REFERENCES renewal(id),
 FOREIGN KEY (account_id) REFERENCES lesson_account(id),
 FOREIGN KEY (created_by) REFERENCES app_user(id),
 FOREIGN KEY (reviewed_by) REFERENCES app_user(id),
 FOREIGN KEY (confirmed_by) REFERENCES app_user(id),
 FOREIGN KEY (ledger_id) REFERENCES lesson_ledger(id),
 CHECK (amount >= 0),
 CHECK (lessons >= 0 AND gift_lessons >= 0 AND lessons + gift_lessons > 0),
 CHECK (status IN ('REQUESTED','APPROVED','REJECTED','CANCELLED','CONFIRMED'))
);
CREATE TABLE refund_log (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 refund_id BIGINT NOT NULL,
 actor_id BIGINT NOT NULL,
 actor_name VARCHAR(80) NOT NULL,
 action VARCHAR(30) NOT NULL,
 from_status VARCHAR(20),
 to_status VARCHAR(20) NOT NULL,
 text VARCHAR(2000) NOT NULL,
 request_key VARCHAR(240) NOT NULL UNIQUE,
 request_hash VARCHAR(64) NOT NULL,
 created_at TIMESTAMP NOT NULL,
 FOREIGN KEY (refund_id) REFERENCES refund_request(id),
 FOREIGN KEY (actor_id) REFERENCES app_user(id)
);
CREATE INDEX idx_refund_account_status ON refund_request(account_id,status);
CREATE INDEX idx_refund_renewal_status ON refund_request(renewal_id,status);

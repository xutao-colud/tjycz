const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const storage = new Map();
let app;
let definition;
let destination = '';
let loginCalls = 0;
let failLogin = false;
let failLogout = false;
let logoutCalls = 0;
let lastCredentials;
let serverRole = 'TEACHER';
global.App = value => { app = value; };
global.Page = value => { definition = value; };
global.getApp = () => app;
global.wx = {
  getStorageSync: key => storage.get(key), setStorageSync: (key, value) => storage.set(key, value), removeStorageSync: key => storage.delete(key),
  stopPullDownRefresh() {}, reLaunch({ url }) { destination = url; }
};
require(path.join(root, 'app.js'));
app.onLaunch();
const api = require(path.join(root, 'utils/api'));
api.health = async () => ({ status: 'UP', demo: true });
api.login = async credentials => {
  loginCalls++;
  lastCredentials = credentials;
  if (failLogin) throw new Error('用户名或密码错误');
  const local = credentials.username === 'admin' && credentials.password === 'admin';
  const role = local ? { PARENT: 'PARENT', TEACHER: 'TEACHER', CAMPUS_ADMIN: 'ADMIN', ADMIN: 'SUPER_ADMIN' }[credentials.role] : serverRole;
  return { token: 'login-test-token', user: { id: 2, name: '样例账号', role }, demo: local };
};
api.demo = async () => { throw new Error('登录页不应再调用免密码演示入口'); };
api.request = async (method, endpoint) => {
  assert.equal(method, 'POST'); assert.equal(endpoint, '/auth/logout');
  logoutCalls++;
  if (failLogout) throw new Error('临时网络离线');
  return { success: true };
};
require(path.join(root, 'pages/login/index.js'));
function screen(query = {}) {
  const page = Object.assign({}, definition, { data: structuredClone(definition.data), setData(patch) { Object.assign(this.data, patch); } });
  page.onLoad(query);
  return page;
}
const event = (dataset = {}) => ({ currentTarget: { dataset } });
async function main() {
  const welcome = screen();
  assert.equal(welcome.data.stage, 'roles', '首次进入直接展示身份选择');
  assert.deepEqual(welcome.data.identities.map(item => item.code), ['PARENT', 'TEACHER', 'CAMPUS_ADMIN', 'ADMIN']);
  assert.equal(screen().data.stage, 'login', '首次看到身份选择后，即使未选身份，再次进入也直达登录页');
  assert.equal(welcome.data.stage, 'roles');
  welcome.selectIdentity(event({ role: 'CAMPUS_ADMIN' }));
  assert.equal(welcome.data.stage, 'login');
  assert.equal(welcome.data.selectedRoleName, '校长');
  assert.equal(screen().data.selectedRole, 'CAMPUS_ADMIN', '再次进入记住上次选择的校长身份');
  welcome.changeIdentity();
  assert.equal(welcome.data.stage, 'roles', '登录页可主动切换身份');
  welcome.skipIdentity();
  assert.equal(welcome.data.stage, 'login');
  welcome.selectIdentity(event({ role: 'INVALID' }));
  assert.equal(welcome.data.selectedRole, 'CAMPUS_ADMIN', '忽略无效身份');
  welcome.selectIdentity(event({ role: 'PARENT' }));
  assert.equal(welcome.data.stage, 'login');
  assert.equal(welcome.data.selectedRole, 'PARENT');
  assert.equal(screen().data.stage, 'login', '完成引导后直接登录');
  assert.equal(screen({ switch: '1' }).data.stage, 'login', '账号管理入口不自动重复身份引导');
  const intro = screen({ stage: 'welcome' });
  intro.start();
  assert.equal(intro.data.stage, 'roles', '显式欢迎页仍可进入身份选择');
  welcome.setData({ username: ' teacher ', password: 'fixture-password' });
  await welcome.submit(event());
  assert.equal(loginCalls, 0, '未同意协议不提交凭证');
  welcome.toggleAgreement();
  welcome.toggleRemember();
  welcome.togglePassword(event());
  assert.equal(welcome.data.showPassword, true);
  await welcome.submit(event());
  assert.deepEqual(lastCredentials, { username: 'teacher', password: 'fixture-password', role: 'PARENT' });
  assert.equal(welcome.data.stage, 'success');
  assert.equal(welcome.data.resultRole, '老师', '正式账号身份由服务端决定');
  assert.equal(welcome.data.selectedRole, 'TEACHER', '正式账号登录后记住服务端身份');
  storage.delete('wanfu.login.intro.v1');
  assert.equal(screen().data.stage, 'login', '已有会话的旧用户直接登录，不重新引导');
  assert.equal(screen().data.selectedRole, 'TEACHER');
  assert.equal(welcome.data.password, '');
  assert.equal(destination, '', '成功页先展示结果，不立即跳转首页');
  assert.equal(storage.get('wanfu.login.account.v1'), 'teacher');
  assert.ok(!JSON.stringify([...storage]).includes('fixture-password'), '不保存密码');
  welcome.resume();
  assert.equal(destination, '/pages/workbench/index');
  const remembered = screen({ switch: '1' });
  assert.equal(remembered.data.username, 'teacher');
  assert.equal(remembered.data.remember, true);
  failLogout = true;
  await remembered.logout();
  assert.equal(app.globalData.session.token, 'login-test-token', '服务端退出失败时保留当前会话以便重试');
  assert.match(remembered.data.error, /服务器会话尚未撤销/);
  assert.equal(remembered.data.busy, false);
  failLogout = false;
  await remembered.logout();
  assert.equal(logoutCalls, 2, '失败重试均须先调用服务端吊销');
  assert.equal(app.globalData.session, null);
  assert.equal(screen().data.stage, 'login', '退出账号后仍直达登录');
  assert.equal(screen().data.selectedRole, 'TEACHER', '退出后保留上次身份');
  failLogin = true;
  remembered.setData({ agreed: true, username: 'teacher', password: 'wrong' });
  await remembered.submit(event());
  assert.equal(remembered.data.stage, 'login');
  assert.equal(remembered.data.error, '用户名或密码错误');
  assert.equal(remembered.data.busy, false);
  assert.equal(app.globalData.session, null);
  failLogin = false;
  remembered.switchMode(event({ mode: 'phone' }));
  remembered.setData({ phone: '13800008888', code: '123456' });
  const beforePhone = loginCalls;
  await remembered.submit(event());
  assert.equal(loginCalls, beforePhone, '手机号未接入时不误调用账号登录接口');
  assert.equal(remembered.data.infoOpen, true);
  assert.match(remembered.data.infoText, /不会发送验证码/);
  remembered.closeInfo();
  remembered.wechat();
  remembered.authorizeWechat();
  assert.equal(remembered.data.stage, 'wechat');
  assert.equal(app.globalData.session, null, '未接入微信不会伪造会话');
  remembered.closeInfo();
  remembered.forgot();
  assert.equal(remembered.data.stage, 'forgot');
  remembered.openReset();
  remembered.resetPassword();
  assert.match(remembered.data.infoText, /未作更改/);
  remembered.closeInfo();
  remembered.back();
  assert.equal(remembered.data.stage, 'forgot');
  for (const role of ['PARENT', 'TEACHER', 'CAMPUS_ADMIN', 'ADMIN']) {
    const local = screen({ stage: 'login', identity: role });
    await local.checkHealth();
    local.setData({ agreed: true, username: 'admin', password: 'admin' });
    await local.submit(event());
    assert.deepEqual(lastCredentials, { username: 'admin', password: 'admin', role });
    assert.equal(app.globalData.session.user.role, { PARENT: 'PARENT', TEACHER: 'TEACHER', CAMPUS_ADMIN: 'ADMIN', ADMIN: 'SUPER_ADMIN' }[role]);
    if (role === 'ADMIN') assert.equal(local.data.resultRole, '老板 / 总管理员');
    if (role === 'CAMPUS_ADMIN') {
      assert.equal(local.data.resultRole, '校区校长');
      assert.equal(require(path.join(root, 'utils/session')).homePage(), 'principal');
      assert.equal(screen().data.selectedRole, 'CAMPUS_ADMIN');
    }
    assert.equal(local.data.stage, 'success');
    await local.logout();
  }
  serverRole = 'ADMIN';
  const principal = screen({ stage: 'login', identity: 'CAMPUS_ADMIN' });
  principal.setData({ agreed: true, username: 'principal', password: 'fixture-password' });
  await principal.submit(event());
  assert.equal(principal.data.resultRole, '校区校长');
  await principal.logout();
  assert.equal(screen().data.selectedRole, 'CAMPUS_ADMIN', '正式校长退出后保留校长身份');
  storage.set('wanfu.login.role.v1', 'INVALID');
  assert.equal(screen().data.selectedRole, 'PARENT', '无效缓存身份回退到有效默认值');
  const localDefault = screen({ stage: 'login' });
  localDefault.setData({ username: '' });
  await localDefault.checkHealth();
  assert.equal(localDefault.data.username, 'admin', '仅本地环境提示统一账号');
  assert.equal(localDefault.data.password, '', '密码仍由用户输入');
  api.health = async () => ({ status: 'UP', demo: false });
  const production = screen({ stage: 'login' });
  await production.checkHealth();
  assert.equal(production.data.demoAvailable, false);
  production.showLegal(event({ kind: 'privacy' }));
  assert.equal(production.data.legalOpen, true);
  production.closeInfo();
  assert.equal(production.data.legalOpen, false);
  console.log('通过登录交互：首次身份选择、后续直达登录、身份记忆与主动切换、家长/老师/校长/管理员四种入口、校长与总管理员区分、正式账号服务端身份、退出吊销与失败恢复、协议/仅记账号/密码显隐及未开通提示。');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
